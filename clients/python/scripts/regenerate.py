"""Regenerates src/cimpal_client/_generated from the CimPal OpenAPI document.

    python scripts/regenerate.py          # rewrite the generated layer
    python scripts/regenerate.py --check  # exit 1 if the committed layer is stale (CI)

The generator is the pinned openapi-python-client in pyproject.toml (dev extra). Every generated
file gets the package's licence header. Never edit the generated files by hand.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PROJECT = Path(__file__).resolve().parent.parent
SPEC = PROJECT.parent.parent / "CimPal-CLI" / "src" / "main" / "resources" / "openapi" / "cimpal-v1.json"
TARGET = PROJECT / "src" / "cimpal_client" / "_generated"
CONFIG = PROJECT / "openapi-generator.yml"
GENERATOR_VERSION = "0.26.1"
HEADER = (
    "# Copyright (c) 2020-2026 gridDigIt Kft.\n"
    "# Licensed under the Apache License, Version 2.0.\n"
    "# SPDX-License-Identifier: Apache-2.0\n"
    f"# Generated by openapi-python-client {GENERATOR_VERSION} from CimPal-CLI/src/main/resources/openapi/"
    "cimpal-v1.json.\n"
    "# Do not edit: run clients/python/scripts/regenerate.py.\n"
)


def generate(into: Path) -> None:
    """Runs the generator into ``into`` and adds the header to every file."""
    # The generator installed next to this Python, never one found on PATH or in the current folder.
    executable = shutil.which("openapi-python-client", path=str(Path(sys.executable).parent))
    if executable is None:
        raise SystemExit("openapi-python-client is not installed next to this Python: pip install -e '.[dev]'")
    command = [executable]
    command += [
        "generate",
        "--path",
        str(SPEC),
        "--meta",
        "none",
        "--output-path",
        str(into),
        "--overwrite",
        "--config",
        str(CONFIG),
    ]
    # The generator warns that the application/zip routes are skipped; the facade covers them, so
    # its output is shown only when it fails.
    # The generator orders some imports by set iteration, which follows string hashing: a fixed seed
    # makes its output the same on every run, so --check is stable.
    env = dict(os.environ, PYTHONHASHSEED="0")
    done = subprocess.run(command, capture_output=True, text=True, env=env)  # noqa: S603 (fixed arguments)
    if done.returncode != 0:
        sys.stderr.write(done.stdout + done.stderr)
        raise SystemExit(done.returncode)
    for file in sorted(into.rglob("*")):
        if file.is_file():
            text = file.read_text(encoding="utf-8").replace("\r\n", "\n")
            if file.suffix == ".py":
                text = HEADER + text
            if file.name == "client.py" and file.parent == into:
                # The generated AuthenticatedClient is an attrs class: keep its token out of repr().
                field_line = "    token: str" + "\n"
                if text.count(field_line) != 1:
                    raise SystemExit("The generated client changed; review the token repr fix in regenerate.py")
                text = text.replace(field_line, "    token: str = field(repr=False)" + "\n")
            file.write_text(text, encoding="utf-8", newline="\n")


def differences(left: Path, right: Path) -> list[str]:
    """Relative paths that differ between two trees (line endings ignored)."""
    names = {p.relative_to(left).as_posix() for p in left.rglob("*") if p.is_file()}
    names |= {p.relative_to(right).as_posix() for p in right.rglob("*") if p.is_file()}

    def text(file: Path) -> str | None:
        return file.read_text(encoding="utf-8").replace("\r\n", "\n") if file.is_file() else None

    return [n for n in sorted(names) if "__pycache__" not in n and text(left / n) != text(right / n)]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only report whether the generated layer is stale")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "_generated"
        generate(fresh)
        if args.check:
            changed = differences(fresh, TARGET)
            if changed:
                print("The generated layer is stale; run clients/python/scripts/regenerate.py. Differs:")
                for name in changed:
                    print("  " + name)
                return 1
            print("The generated layer matches cimpal-v1.json.")
            return 0
        shutil.rmtree(TARGET, ignore_errors=True)
        shutil.copytree(fresh, TARGET)
    print(f"Regenerated {TARGET.relative_to(PROJECT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
